"""Prediction and portfolio metrics.

Two families are deliberately kept separate:

``prediction_metrics``
    Statistical accuracy of the return forecast.  Ordinary scikit-learn R^2 is
    computed against the *evaluation sample mean*; ``r2_oos_trainmean`` is the
    benchmark-relative out-of-sample R^2 that uses the **training** mean as the
    naive forecast (Campbell-Thompson style), so it cannot look at validation
    or test labels to form its baseline.

``portfolio_metrics``
    Post-cost trading performance generated by the unchanged original rules
    (Top-10, equal weight, next-open execution, 20 bps per traded side).

All return metrics are computed from the per-period net return series.  When
no risk-free series is supplied, Sharpe/Sortino/alpha are explicitly labelled
as zero-risk-free approximations rather than true excess-return statistics.
"""
from __future__ import annotations

from typing import Any, Dict, Mapping, Optional, Sequence

import numpy as np
import pandas as pd

ANNUALIZATION = {"monthly": 12, "quarterly": 4, "semiannual": 2, "annual": 1}


def _finite_pair(y_true: Sequence[float], y_pred: Sequence[float]):
    y_true = np.asarray(y_true, dtype=float)
    y_pred = np.asarray(y_pred, dtype=float)
    mask = np.isfinite(y_true) & np.isfinite(y_pred)
    return y_true[mask], y_pred[mask]


def _safe_divide(numerator: float, denominator: float) -> float:
    if denominator is None or not np.isfinite(denominator) or abs(denominator) < 1e-15:
        return float("nan")
    return float(numerator / denominator)


def prediction_metrics(
    y_true: Sequence[float],
    y_pred: Sequence[float],
    train_mean: float,
    dates: Optional[Sequence[Any]] = None,
) -> Dict[str, Any]:
    """MSE/RMSE/MAE, two R^2 definitions, direction and rank-IC diagnostics."""
    y, p = _finite_pair(y_true, y_pred)
    n = int(len(y))
    out: Dict[str, Any] = {
        "n_obs": n,
        "n_dates": int(pd.Series(dates).nunique()) if dates is not None else np.nan,
        "mse": np.nan,
        "rmse": np.nan,
        "mae": np.nan,
        "r2_sklearn": np.nan,
        "r2_oos_trainmean": np.nan,
        "directional_accuracy": np.nan,
        "directional_accuracy_cs": np.nan,
        "pearson_corr": np.nan,
        "spearman_rank_ic_pooled": np.nan,
        "mean_rank_ic": np.nan,
        "rank_ic_std": np.nan,
        "rank_ic_positive_share": np.nan,
        "mean_prediction": np.nan,
        "mean_target": np.nan,
        "prediction_bias": np.nan,
    }
    if n == 0:
        return out

    residual = y - p
    sse = float(np.sum(residual**2))
    out["mse"] = float(np.mean(residual**2))
    out["rmse"] = float(np.sqrt(out["mse"]))
    out["mae"] = float(np.mean(np.abs(residual)))
    out["mean_prediction"] = float(np.mean(p))
    out["mean_target"] = float(np.mean(y))
    out["prediction_bias"] = float(np.mean(p - y))

    sst_sample = float(np.sum((y - np.mean(y)) ** 2))
    out["r2_sklearn"] = 1.0 - _safe_divide(sse, sst_sample) if sst_sample > 0 else np.nan

    # Benchmark-relative OOS R^2: naive forecast is the TRAINING mean.
    sst_train = float(np.sum((y - float(train_mean)) ** 2))
    out["r2_oos_trainmean"] = 1.0 - _safe_divide(sse, sst_train) if sst_train > 0 else np.nan

    out["directional_accuracy"] = float(np.mean(np.sign(p) == np.sign(y)))

    if n > 1 and np.std(p) > 0 and np.std(y) > 0:
        out["pearson_corr"] = float(np.corrcoef(p, y)[0, 1])

    if dates is not None:
        mask = np.isfinite(np.asarray(y_true, dtype=float)) & np.isfinite(np.asarray(y_pred, dtype=float))
        frame = pd.DataFrame(
            {
                "date": np.asarray(dates)[mask],
                "y": np.asarray(y_true, dtype=float)[mask],
                "p": np.asarray(y_pred, dtype=float)[mask],
            }
        )
        ics, direction = [], []
        for _, group in frame.groupby("date"):
            if len(group) < 3:
                continue
            if group.y.std() > 0 and group.p.std() > 0:
                ics.append(float(group.p.corr(group.y, method="spearman")))
            yd = group.y - group.y.mean()
            pd_ = group.p - group.p.mean()
            direction.append(float(np.mean(np.sign(pd_) == np.sign(yd))))
        if ics:
            out["mean_rank_ic"] = float(np.mean(ics))
            out["rank_ic_std"] = float(np.std(ics, ddof=1)) if len(ics) > 1 else np.nan
            out["rank_ic_positive_share"] = float(np.mean(np.array(ics) > 0))
        if direction:
            out["directional_accuracy_cs"] = float(np.mean(direction))
        if len(frame) > 2 and frame.y.std() > 0 and frame.p.std() > 0:
            out["spearman_rank_ic_pooled"] = float(frame.p.corr(frame.y, method="spearman"))
    return out


def _max_drawdown(wealth: pd.Series) -> float:
    if wealth.empty:
        return float("nan")
    return float((wealth / wealth.cummax() - 1.0).min())


def drawdown_series(returns: pd.Series) -> pd.Series:
    wealth = (1.0 + returns.fillna(0.0)).cumprod()
    return wealth / wealth.cummax() - 1.0


def portfolio_metrics(
    returns: pd.DataFrame,
    strategy: str,
    frequency: str = "monthly",
    benchmark: str = "SPY",
    risk_free_rate: Optional[float] = None,
) -> Dict[str, Any]:
    """Comprehensive post-cost metrics for one strategy.

    ``returns`` must contain one row per period with columns
    ``strategy, decision_date, gross_return, net_return, cost,
    turnover_two_way``.
    """
    annual = ANNUALIZATION[frequency]
    frame = returns.loc[returns.strategy == strategy].sort_values("decision_date")
    out: Dict[str, Any] = {
        "strategy": strategy,
        "n_periods": int(len(frame)),
        "frequency": frequency,
        "risk_free_assumption": "zero" if risk_free_rate is None else f"{risk_free_rate}",
        "sharpe_definition": "zero-risk-free approximation" if risk_free_rate is None else "excess-return Sharpe",
    }
    base_keys = [
        "total_return_gross",
        "total_return_net",
        "annualized_return",
        "annualized_return_gross",
        "average_period_return",
        "median_period_return",
        "annualized_volatility",
        "annualized_downside_deviation",
        "sharpe_ratio",
        "sortino_ratio",
        "max_drawdown",
        "calmar_ratio",
        "average_turnover",
        "total_transaction_cost",
        "average_period_transaction_cost",
        "positive_period_share",
        "best_period_return",
        "worst_period_return",
        "benchmark_relative_annualized_return",
        "tracking_error",
        "information_ratio",
        "beta_to_benchmark",
        "alpha_annualized",
        "correlation_to_benchmark",
        "benchmark",
        "benchmark_annualized_return",
    ]
    for key in base_keys:
        out[key] = np.nan
    if frame.empty:
        return out

    r = frame.net_return.astype(float)
    gross = frame.gross_return.astype(float)
    n = len(r)
    wealth = (1.0 + r).cumprod()
    wealth_gross = (1.0 + gross).cumprod()
    total_net = float(wealth.iloc[-1] - 1.0)
    total_gross = float(wealth_gross.iloc[-1] - 1.0)
    mean_r = float(r.mean())
    std_r = float(r.std(ddof=1)) if n > 1 else np.nan
    downside = float(np.sqrt(np.mean(np.minimum(r.to_numpy(), 0.0) ** 2))) if n > 0 else np.nan
    mdd = _max_drawdown(wealth)
    cagr = float((1.0 + total_net) ** (annual / n) - 1.0) if (1.0 + total_net) > 0 else np.nan
    cagr_gross = float((1.0 + total_gross) ** (annual / n) - 1.0) if (1.0 + total_gross) > 0 else np.nan

    out.update(
        {
            "n_periods": int(n),
            "total_return_gross": total_gross,
            "total_return_net": total_net,
            "annualized_return": cagr,
            "annualized_return_gross": cagr_gross,
            "average_period_return": mean_r,
            "median_period_return": float(r.median()),
            "annualized_volatility": float(std_r * np.sqrt(annual)) if np.isfinite(std_r) else np.nan,
            "annualized_downside_deviation": float(downside * np.sqrt(annual)) if np.isfinite(downside) else np.nan,
            "sharpe_ratio": float(_safe_divide(mean_r, std_r) * np.sqrt(annual)) if np.isfinite(std_r) else np.nan,
            "sortino_ratio": float(_safe_divide(mean_r, downside) * np.sqrt(annual)) if np.isfinite(downside) else np.nan,
            "max_drawdown": mdd,
            "calmar_ratio": float(_safe_divide(cagr, abs(mdd))) if np.isfinite(mdd) and mdd < 0 else np.nan,
            "average_turnover": float(frame.turnover_two_way.mean()),
            "total_transaction_cost": float(frame.cost.sum()),
            "average_period_transaction_cost": float(frame.cost.mean()),
            "positive_period_share": float(np.mean(r > 0)),
            "best_period_return": float(r.max()),
            "worst_period_return": float(r.min()),
        }
    )

    bench = returns.loc[returns.strategy == benchmark].set_index("decision_date").net_return
    # Align on decision dates: ``r`` still carries the original row index, so
    # it must be re-indexed before the inner join with the benchmark series.
    strategy_series = frame.set_index("decision_date").net_return.astype(float)
    aligned = pd.concat(
        [strategy_series.rename("r"), bench.rename("b")], axis=1, join="inner"
    ).dropna()
    if len(aligned) > 1:
        b = aligned.b
        bench_wealth = (1.0 + b).cumprod()
        bench_cagr = float(bench_wealth.iloc[-1] ** (annual / len(b)) - 1.0)
        active = aligned.r - aligned.b
        std_active = float(active.std(ddof=1))
        var_b = float(b.var(ddof=1))
        beta = float(_safe_divide(float(np.cov(aligned.r, aligned.b, ddof=1)[0, 1]), var_b))
        alpha_period = float(mean_r - beta * float(b.mean()))
        out.update(
            {
                "benchmark": benchmark,
                "benchmark_annualized_return": bench_cagr,
                "benchmark_relative_annualized_return": float(cagr - bench_cagr),
                "tracking_error": float(std_active * np.sqrt(annual)),
                "information_ratio": float(_safe_divide(float(active.mean()), std_active) * np.sqrt(annual)),
                "beta_to_benchmark": beta,
                "alpha_annualized": float((1.0 + alpha_period) ** annual - 1.0),
                "correlation_to_benchmark": float(aligned.r.corr(aligned.b)),
            }
        )
    return out


def annual_returns(returns: pd.DataFrame, strategy: str | None = None) -> pd.DataFrame:
    frame = returns if strategy is None else returns.loc[returns.strategy == strategy]
    frame = frame.copy()
    frame["year"] = pd.to_datetime(frame.decision_date).dt.year
    grouped = frame.groupby(["strategy", "year"]).net_return.apply(lambda s: float((1.0 + s).prod() - 1.0))
    return grouped.unstack("year")


def metric_definitions() -> Dict[str, str]:
    """Human-readable formulas, reused by the README and the notebook."""
    return {
        "MSE": "mean((y_true - y_pred)^2)",
        "RMSE": "sqrt(MSE)",
        "MAE": "mean(|y_true - y_pred|)",
        "R2_sklearn": "1 - SSE / sum((y - mean(y_eval))^2)  [ordinary sklearn R^2]",
        "R2_oos_trainmean": "1 - SSE / sum((y - mean(y_train))^2)  [naive forecast = training mean]",
        "DirectionalAccuracy": "mean(sign(y_pred) == sign(y_true))",
        "DirectionalAccuracyCS": "same sign test after demeaning predictions and outcomes within each decision date",
        "RankIC": "Spearman correlation of predictions and outcomes within a decision date",
        "TotalReturn": "prod(1 + net_return) - 1",
        "CAGR": "(1 + total_return)^(periods_per_year / n_periods) - 1",
        "AnnualizedVolatility": "std(net_return, ddof=1) * sqrt(periods_per_year)",
        "Sharpe_rf0": "mean(net_return) / std(net_return, ddof=1) * sqrt(periods_per_year)",
        "Sortino_rf0": "mean(net_return) / sqrt(mean(min(net_return, 0)^2)) * sqrt(periods_per_year)",
        "MaxDrawdown": "min(wealth / cummax(wealth) - 1)",
        "Calmar": "CAGR / |MaxDrawdown|",
        "Turnover": "sum(|target_weight - pretrade_weight|) per rebalance (one-way weight traded)",
        "TransactionCost": "turnover * 20bps",
        "TrackingError": "std(r_strategy - r_benchmark, ddof=1) * sqrt(periods_per_year)",
        "InformationRatio": "mean(r_strategy - r_benchmark) / std(r_strategy - r_benchmark, ddof=1) * sqrt(periods_per_year)",
        "Beta": "cov(r_strategy, r_SPY) / var(r_SPY)",
        "AlphaAnnualized": "(1 + mean(r_strategy) - beta * mean(r_SPY))^periods_per_year - 1",
    }
